/** その年の説明。用意がない年は直前の年の説明を返す */
export function yearGuideFor(year: number): YearGuide | null {
  if (YEAR_GUIDES[year]) return YEAR_GUIDES[year];
  const earlier = Object.keys(YEAR_GUIDES)
    .map(Number)
    .filter((y) => y < year)
    .sort((a, b) => b - a);
  return earlier.length > 0 ? YEAR_GUIDES[earlier[0]] : null;
}

export type TodoItem = { id: string; title: string; due: string; body: string };

/** その年にやること。見込み（estimate）で、当てはまるものだけを日付順に並べる */
export function buildTodos(year: number, e: TaxEstimate): TodoItem[] {
  const next = year + 1;
  const todos: TodoItem[] = [];
  const salaried = e.income.salary > 0;
  if (salaried) {
    todos.push({
      id: "yearEndDocs",
      title: "年末調整の書類を勤め先に出す",
      due: `${year}-11-30`,
      body: "扶養控除等（異動）申告書、基礎控除申告書・配偶者控除等申告書、保険料控除申告書、住宅借入金等特別控除申告書（2 年目以後）。家族の所得の見込みも確かめます。",
    });
  }
  todos.push({
    id: "certificates",
    title: "控除証明書を集める",
    due: `${year}-11-30`,
    body: "生命保険料・地震保険料・国民年金保険料の控除証明書、iDeCo の掛金払込証明書は 10〜11 月ごろに届きます。",
  });
  todos.push({
    id: "furusatoDonate",
    title: "ふるさと納税の上限を確かめて寄附する",
    due: `${year}-12-31`,
    body:
      e.furusato.limit > 0
        ? `上限の目安は ${e.furusato.limit.toLocaleString()} 円、残り ${e.furusato.remaining.toLocaleString()} 円です。12 月 31 日までの入金が今年分です。`
        : "所得割の住民税がかからない見込みのため、ふるさと納税で税は戻りません。",
  });
  if (e.furusato.path === "oneStop") {
    todos.push({
      id: "oneStopForm",
      title: "ワンストップ特例の申請書を寄附先に送る",
      due: `${next}-01-10`,
      body: "寄附先ごとに申請書（と本人確認書類）を送ります。オンライン申請に対応した自治体もあります。",
    });
  }
  todos.push({
    id: "medicalTotal",
    title: "医療費・対象の市販薬を集計する",
    due: `${year}-12-31`,
    body: "家族の分も合わせて、医療費が 10 万円（所得 200 万円未満は所得の 5%）を超えるか、対象の市販薬が 1.2 万円を超えるかを確かめます。",
  });
  todos.push({
    id: "investmentLimits",
    title: "iDeCo・NISA の年内の枠を確かめる",
    due: `${year}-12-31`,
    body: "iDeCo の掛金は年内に払った分がその年の控除になります。NISA の年間投資枠は翌年に繰り越せません。",
  });
  if (salaried) {
    todos.push({
      id: "withholdingSlip",
      title: "源泉徴収票を受け取る",
      due: `${next}-01-31`,
      body: "年末調整の結果が載っています。このページの給与収入・源泉徴収税額を源泉徴収票の額で上書きすると見込みが正確になります。",
    });
  }
  if (e.filing.willFile) {
    todos.push({
      id: "taxReturn",
      title: "確定申告をする",
      due: `${next}-03-15`,
      body: `申告期間は ${next} 年 2 月 16 日〜3 月 15 日（土日の場合は翌平日）。還付だけの申告は 1 月 1 日から出せて、5 年間さかのぼれます。e-Tax なら確定申告書等作成コーナーから提出できます。`,
    });
  }
  if (e.furusato.donated > 0) {
    todos.push({
      id: "residentNotice",
      title: "住民税の決定通知書で寄附金税額控除を確かめる",
      due: `${next}-06-30`,
      body: "6 月ごろに届く通知書（給与からの天引きなら勤め先経由）の「寄附金税額控除」の欄で、ふるさと納税の分が引かれているか確かめます。",
    });
  }
  return todos.sort((a, b) => a.due.localeCompare(b.due));
}
