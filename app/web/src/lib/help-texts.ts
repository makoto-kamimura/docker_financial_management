/** KPI カードの累計（YTD）と年間見込みの説明。income / profit はモードごとの呼び方 */
export function kpiTermHelp(mode: ViewMode) {
  const { revenue: income, profit } = KPI_LABELS[mode];
  const outlook =
    `1年は、設定の「決算月」で締める期で数えます（既定は12月決算＝1〜12月）。` +
    `入力の無い月はその期で入力のある月の平均で埋め、まだ来ていない月は直近3か月の平均で見積もります。` +
    `実績を確定した月より後は、入力があっても見積もりで数えます（確定を使っていない場合は選んだ月まで実績）。` +
    `1か月分の入力だけでも、1年分の目安がわかります。`;
  return {
    ytd:
      `期のはじめ（12月決算なら1月）から選んだ月までの${income}の合計です（Year To Date）。` +
      `「年間見込み」は、この合計に入力の無い月と残りの月の見積もりを足した1年分の金額で、` +
      `「達成率」は年間見込みに対する今の合計の割合です。` +
      outlook,
    profit: `「年間見込み」は、${profit}を1年分に見積もった金額です。` + outlook,
  };
}

